import { writeFile } from 'node:fs/promises';
import { entries, root } from './catalog.mjs';
import path from 'node:path';

const catalog = await entries();
const groups = [...new Set(catalog.map(entry => entry.category))];
const count = catalog.reduce((sum, entry) => sum + entry.captures.length, 0);
let markdown = `# Catalog index\n\n${catalog.length} runnable examples · ${count} original captures. Generated by \`npm run sync\`.\n\nCaptures record exact runtime versions; a dash means capture work is pending. Newer-API examples require the minimum OS shown. See [the roadmap](ROADMAP.md) for the full scope and remaining coverage.\n`;
for (const category of groups) {
  markdown += `\n## ${category}\n\n| Example | Minimum iOS | Captured runtimes |\n| --- | --- | --- |\n`;
  for (const entry of catalog.filter(entry => entry.category === category)) {
    const location = path.relative(root, entry.directory);
    const versions = [...new Set(entry.captures.map(capture => capture.os))].sort((a, b) => a.localeCompare(b, undefined, { numeric: true }));
    markdown += `| [${entry.title}](${location}/README.md) | ${entry.demoMinIOS} | ${versions.join(', ') || '—'} |\n`;
  }
}
await writeFile(path.join(root, 'CATALOG.md'), markdown);
console.log(`Indexed ${catalog.length} examples and ${count} captures.`);
