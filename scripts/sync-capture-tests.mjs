import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { entries, root } from './catalog.mjs';

const catalog = await entries();
const skipExisting = process.argv.includes('--skip-existing');
for (const entry of catalog) {
  const hash = createHash('sha256').update(await readFile(path.join(entry.directory, entry.swiftFile))).digest('hex');
  entry.capturedVersions = skipExisting ? [...new Set(entry.captures.filter(c => c.sourceSHA256 === hash && c.device.startsWith('iPhone') && !c.device.includes('Duo')).map(c => Number(c.os.split('.')[0])))] : [];
}
const quote = JSON.stringify;
const tests = `// Generated by npm run sync. One native capture test per catalog entry.
import XCTest
import Foundation
import StoreKitTest

@MainActor
final class CatalogCaptureTests: XCTestCase {
    private var storeKitSession: SKTestSession?
    override func setUpWithError() throws { continueAfterFailure = false }

    override func tearDownWithError() throws { storeKitSession = nil }

    private func configureLocalStoreKit() throws {
        let fixture = try XCTUnwrap(Bundle(for: type(of: self)).url(forResource: "AtlasPurchases", withExtension: "storekit"), "Missing local StoreKit fixture")
        let session = try SKTestSession(contentsOf: fixture)
        session.resetToDefaultState()
        session.clearTransactions()
        session.locale = Locale(identifier: "en_US")
        session.storefront = "USA"
        session.timeRate = .realTime
        session.disableDialogs = false
        storeKitSession = session
    }

    private func capture(_ id: String, minimumMajor: Int, minimumMinor: Int, action: String? = nil, readyLabel: String? = nil, keyboard: Bool = false, scroll: Bool = false, storeKit: Bool = false, capturedVersions: [Int] = []) throws {
        let minimum = OperatingSystemVersion(majorVersion: minimumMajor, minorVersion: minimumMinor, patchVersion: 0)
        try XCTSkipUnless(ProcessInfo.processInfo.isOperatingSystemAtLeast(minimum), "Requires iOS \\(minimumMajor).\\(minimumMinor)")
        try XCTSkipIf(capturedVersions.contains(ProcessInfo.processInfo.operatingSystemVersion.majorVersion), "This source already has a verified iPhone capture on this OS generation")
        if storeKit { try configureLocalStoreKit() }
        let app = XCUIApplication()
        app.launchArguments = ["--entry", id, "--capture", "-AppleLanguages", "(en)", "-AppleLocale", "en_US"]
        app.launch()
        defer { app.terminate() }
        if storeKit {
            XCTAssertTrue(app.descendants(matching: .any).matching(identifier: "storekit-products-loaded").firstMatch.waitForExistence(timeout: 30), "Local StoreKit products did not load")
        }
        if let action {
            let trigger = app.descendants(matching: .any).matching(identifier: "capture-open").firstMatch
            XCTAssertTrue(trigger.waitForExistence(timeout: 10), "Missing capture interaction")
            if action == "longPress" { trigger.press(forDuration: 1) } else { trigger.tap() }
        }
        if ["alert-actions", "alert-text-fields"].contains(id) {
            XCTAssertTrue(app.alerts.firstMatch.waitForExistence(timeout: 10), "Missing native alert")
        } else if let readyLabel {
            XCTAssertTrue(app.buttons[readyLabel].waitForExistence(timeout: 12), "Missing system action")
        } else {
            XCTAssertTrue(app.descendants(matching: .any).matching(identifier: "capture-ready").firstMatch.waitForExistence(timeout: 12), "Capture content did not appear for \\(id)")
        }
        if scroll {
            let scrollView = app.scrollViews.firstMatch
            XCTAssertTrue(scrollView.waitForExistence(timeout: 5), "Missing scroll view")
            scrollView.swipeUp()
        }
        if keyboard && !app.keyboards.firstMatch.waitForExistence(timeout: 2) {
            let markedField = app.descendants(matching: .any).matching(identifier: "capture-focus").firstMatch
            if markedField.exists { markedField.tap() }
            else if app.searchFields.firstMatch.exists { app.searchFields.firstMatch.tap() }
            else if app.textViews.firstMatch.exists { app.textViews.firstMatch.tap() }
            else { app.textFields.firstMatch.tap() }
        }
        if keyboard { XCTAssertTrue(app.keyboards.firstMatch.waitForExistence(timeout: 5), "Software keyboard is not visible") }
        // Preserve native animations; record only after the transition settles.
        Thread.sleep(forTimeInterval: 1.5)
        let attachment = XCTAttachment(screenshot: XCUIScreen.main.screenshot())
        attachment.name = "atlas--\\(id)--default"
        attachment.lifetime = .keepAlways
        add(attachment)
    }

${catalog.map(entry => {
  const [major, minor = 0] = entry.demoMinIOS.split('.').map(Number);
  if (entry.captureManual) return `    func testCapture_${entry.id.replaceAll('-', '_')}() throws {
        throw XCTSkip(${quote(entry.captureManualReason)})
    }`;
  return `    func testCapture_${entry.id.replaceAll('-', '_')}() throws {
        try capture(${quote(entry.id)}, minimumMajor: ${major}, minimumMinor: ${minor}, action: ${entry.captureAction ? quote(entry.captureAction) : "nil"}, readyLabel: ${entry.captureReadyLabel ? quote(entry.captureReadyLabel) : "nil"}, keyboard: ${entry.captureKeyboard ?? false}, scroll: ${entry.captureScroll ?? false}, storeKit: ${entry.captureStoreKit ?? false}, capturedVersions: ${JSON.stringify(entry.capturedVersions)})
    }`;
}).join('\n\n')}
}
`;
await writeFile(path.join(root, 'app/Atlas/AtlasUITests/CatalogCaptureTests.generated.swift'), tests);
console.log(`Synced ${catalog.length} native capture tests with runtime availability checks.`);
