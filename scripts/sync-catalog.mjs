import { mkdir, writeFile, symlink, readdir, lstat, readlink, unlink } from 'node:fs/promises';
import path from 'node:path';
import { entries, root } from './catalog.mjs';

const catalog = await entries();
const destination = path.join(root, 'app/Atlas/Atlas/Examples');
await mkdir(destination, { recursive: true });
const expected = new Set(catalog.map(entry => entry.swiftFile));
for (const name of await readdir(destination)) {
  const file = path.join(destination, name);
  if (!expected.has(name) && (await lstat(file)).isSymbolicLink()) await unlink(file);
}
for (const entry of catalog) {
  const file = path.join(destination, entry.swiftFile);
  const target = path.relative(destination, path.join(entry.directory, entry.swiftFile));
  try {
    if (await readlink(file) === target) continue;
    await unlink(file);
  } catch (error) { if (error.code !== 'ENOENT') throw error; }
  await symlink(target, file);
}
const quote = value => JSON.stringify(value).replace(/\\u([0-9a-f]{4})/g, '\\u{$1}');
const captureNavigation = entry => entry.captureNavigation ?? !['alert-actions', 'alert-text-fields'].includes(entry.id);
const swift = `// Generated by npm run sync from catalog/**/README.md. Do not edit.
import SwiftUI

struct AtlasEntry: Identifiable, Hashable {
    let id: String
    let title: String
    let summary: String
    let category: String
    let family: String
    let apis: [String]
    let minimumOS: String
    let captureNavigation: Bool
    let ownsNavigation: Bool

    var isSupported: Bool {
        let components = minimumOS.split(separator: ".").compactMap { Int($0) }
        return ProcessInfo.processInfo.isOperatingSystemAtLeast(
            OperatingSystemVersion(majorVersion: components[0], minorVersion: components.count > 1 ? components[1] : 0, patchVersion: 0)
        )
    }
}

enum AtlasCatalog {
    static let entries: [AtlasEntry] = [
${catalog.map(e => `        AtlasEntry(id: ${quote(e.id)}, title: ${quote(e.title)}, summary: ${quote(e.summary)}, category: ${quote(e.category)}, family: ${quote(e.family)}, apis: [${e.apis.map(quote).join(', ')}], minimumOS: ${quote(e.demoMinIOS)}, captureNavigation: ${captureNavigation(e)}, ownsNavigation: ${e.ownsNavigation ?? false}),`).join('\n')}
    ]

    @MainActor @ViewBuilder
    static func demo(for id: String) -> some View {
        switch id {
${catalog.map(e => `        case ${quote(e.id)}:
            if #available(iOS ${e.demoMinIOS}, *) { ${e.view}() }
            else { ContentUnavailableView("Requires iOS ${e.demoMinIOS}", systemImage: "iphone", description: Text("Run this example on a newer simulator or device.")) }`).join('\n')}
        default: ContentUnavailableView("Example unavailable", systemImage: "questionmark.folder")
        }
    }
}
`;
await writeFile(path.join(root, 'app/Atlas/Atlas/Catalog.generated.swift'), swift);
console.log(`Synced ${catalog.length} entries; Swift sources are symlinked, never copied.`);
