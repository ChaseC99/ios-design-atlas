import { mkdir, writeFile, symlink, readdir, lstat, readlink, unlink } from 'node:fs/promises';
import path from 'node:path';
import { entries, root } from './catalog.mjs';

const catalog = await entries();
const destination = path.join(root, 'app/Atlas/Atlas/Examples');
await mkdir(destination, { recursive: true });
const expected = new Set(catalog.map(entry => entry.swiftFile));
for (const name of await readdir(destination)) {
  const file = path.join(destination, name);
  if (!expected.has(name) && (await lstat(file)).isSymbolicLink()) await unlink(file);
}
for (const entry of catalog) {
  const file = path.join(destination, entry.swiftFile);
  const target = path.relative(destination, path.join(entry.directory, entry.swiftFile));
  try {
    if (await readlink(file) === target) continue;
    await unlink(file);
  } catch (error) { if (error.code !== 'ENOENT') throw error; }
  await symlink(target, file);
}
const quote = value => JSON.stringify(value).replace(/\\u([0-9a-f]{4})/g, '\\u{$1}');
const swift = `// Generated by npm run sync from catalog/**/README.md. Do not edit.\nimport SwiftUI\n\nstruct AtlasEntry: Identifiable, Hashable {\n    let id: String\n    let title: String\n    let summary: String\n    let family: String\n    let apis: [String]\n}\n\nenum AtlasCatalog {\n    static let entries: [AtlasEntry] = [\n${catalog.map(e => `        AtlasEntry(id: ${quote(e.id)}, title: ${quote(e.title)}, summary: ${quote(e.summary)}, family: ${quote(e.family)}, apis: [${e.apis.map(quote).join(', ')}]),`).join('\n')}\n    ]\n\n    @MainActor @ViewBuilder\n    static func demo(for id: String) -> some View {\n        switch id {\n${catalog.map(e => `        case ${quote(e.id)}: ${e.view}()`).join('\n')}\n        default: ContentUnavailableView("Example unavailable", systemImage: "questionmark.folder")\n        }\n    }\n}\n`;
await writeFile(path.join(root, 'app/Atlas/Atlas/Catalog.generated.swift'), swift);
console.log(`Synced ${catalog.length} entries; Swift sources are symlinked, never copied.`);
